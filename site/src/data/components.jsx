// 扁平化所有组件，方便查找
export const allComponents = componentCategories.flatMap((cat) =>
  cat.components.map((c) => ({ ...c, category: cat.name }))
)

// 根据 id 查找组件
export function getComponentById(id) {
  return allComponents.find((c) => c.id === id)
}

// 获取相邻组件（用于上一页/下一页导航）
export function getAdjacentComponents(id) {
  const index = allComponents.findIndex((c) => c.id === id)
  return {
    prev: index > 0 ? allComponents[index - 1] : null,
    next: index < allComponents.length - 1 ? allComponents[index + 1] : null,
  }
}
